export function hasConfirmedWarehouse(address = warehouse): boolean {
  return address.confirmed &&
    ["Получатель", "Телефон", "Регион", "Адрес", "Индекс"].every((label) =>
      address.lines.some((line) => line.label === label && line.value.trim() !== ""),
    ) &&
    ["Получатель", "Адрес"].every((label) =>
      address.lines.some((line) => line.label === label && line.value.includes("{code}")),
    );
}

